<?php
/**
 * Gold market widget (vertical slider).
 *
 * Variables (extracted by WidgetBase::renderPartial):
 * @var array<int, array{symbol: string, label: string, price: float|null,
 *     change: float|null, change_percent: float|null, buyback: float|null,
 *     updated_at: int|null, source: string}> $quotes
 * @var string $source Source label.
 * @var int|null $updated_at Newest snapshot timestamp.
 * @var string $currency Currency code (e.g. "IDR").
 * @var string $unit Unit label (e.g. "per gram").
 *
 * Slider behaviour (auto-scroll, play/pause, prev/next, dots) lives in
 * the frontend `sliders.ts` module, driven by its data attributes:
 * the root carries `data-slider="vertical"`, the list is
 * `data-slider-track`, and the controls are `data-slider-prev`,
 * `data-slider-next` and `data-slider-toggle` (with
 * `data-label-pause` / `data-label-play`); dots are generated by that
 * module into `data-slider-dots`. Slides have a fixed height (see
 * resources/css/components/widgets.css) so the vertical step is
 * uniform; keep each slide to one brand with compact lines.
 */
declare(strict_types=1);

?>
<div class="widget-market widget-gold-market" data-slider="vertical">
    <?php if (!empty($quotes)) : ?>
        <div class="market-slider" role="region"
            aria-label="<?php esc_attr_e('Gold prices', 'traydigita-core'); ?>">
            <ul class="market-slides" data-slider-track>
                <?php foreach ($quotes as $index => $quote) : ?>
                    <?php
                    $direction = ($quote['change'] ?? null) === null || (float) $quote['change'] === 0.0
                        ? 'flat'
                        : ((float) $quote['change'] > 0 ? 'up' : 'down');
                    ?>
                    <li class="market-slide market-slide-<?php echo esc_attr($direction); ?>"
                        data-market-slide="<?php echo esc_attr((string) $index); ?>">
                        <span class="market-label"><?php echo esc_html($quote['label']); ?></span>
                        <?php if ($quote['price'] !== null) : ?>
                            <span class="market-price">
                                <?php echo esc_html('Rp' . number_format_i18n((float) $quote['price'], 0)); ?>
                            </span>
                            <span class="market-unit"><?php echo esc_html($unit); ?></span>
                        <?php else : ?>
                            <span class="market-price market-price-unavailable">
                                <?php esc_html_e('Price unavailable', 'traydigita-core'); ?>
                            </span>
                        <?php endif; ?>
                        <?php if ($quote['buyback'] !== null) : ?>
                            <span class="market-buyback">
                                <?php
                                echo esc_html(
                                    sprintf(
                                        /* translators: %s is the buyback price. */
                                        __('Buyback: %s', 'traydigita-core'),
                                        'Rp' . number_format_i18n((float) $quote['buyback'], 0)
                                    )
                                );
                                ?>
                            </span>
                        <?php endif; ?>
                        <?php if ($quote['change'] !== null) : ?>
                            <span class="market-change market-change-<?php echo esc_attr($direction); ?>">
                                <?php
                                $changeText = ($direction === 'up' ? '+' : '')
                                    . 'Rp' . number_format_i18n((float) $quote['change'], 0);
                                if ($quote['change_percent'] !== null) {
                                    $changeText .= ' (' . ($direction === 'up' ? '+' : '')
                                        . number_format_i18n((float) $quote['change_percent'], 2) . '%)';
                                }
                                $changeText .= $direction === 'up'
                                    ? ' ' . __('Up', 'traydigita-core')
                                    : ($direction === 'down'
                                        ? ' ' . __('Down', 'traydigita-core')
                                        : ' ' . __('Unchanged', 'traydigita-core'));
                                echo esc_html($changeText);
                                ?>
                            </span>
                        <?php endif; ?>
                    </li>
                <?php endforeach; ?>
            </ul>
            <div class="market-controls">
                <button type="button" class="market-control market-prev"
                    data-slider-prev aria-label="<?php esc_attr_e('Previous brand', 'traydigita-core'); ?>">
                    <svg class="icon-small" aria-hidden="true"><use href="#td-icon-prev" /></svg>
                </button>
                <button type="button" class="market-control market-play-pause"
                    data-slider-toggle
                    aria-label="<?php esc_attr_e('Pause auto-scroll', 'traydigita-core'); ?>"
                    data-label-pause="<?php esc_attr_e('Pause auto-scroll', 'traydigita-core'); ?>"
                    data-label-play="<?php esc_attr_e('Play auto-scroll', 'traydigita-core'); ?>">
                    <svg class="icon-small" aria-hidden="true"><use href="#td-icon-pause" /></svg>
                </button>
                <button type="button" class="market-control market-next"
                    data-slider-next aria-label="<?php esc_attr_e('Next brand', 'traydigita-core'); ?>">
                    <svg class="icon-small" aria-hidden="true"><use href="#td-icon-next" /></svg>
                </button>
            </div>
            <div class="market-dots" data-slider-dots role="tablist"
                aria-label="<?php esc_attr_e('Choose brand', 'traydigita-core'); ?>">
            </div>
        </div>
        <p class="market-source">
            <?php
            echo esc_html(
                sprintf(
                    /* translators: 1: source label. 2: update time. */
                    __('Source: %1$s · Updated %2$s', 'traydigita-core'),
                    $source,
                    $updated_at !== null
                        ? \TrayDigita\WP\Plugin\Core\Widgets\WeatherHelper::formatUpdatedAt((int) $updated_at)
                        : __('never', 'traydigita-core')
                )
            );
            ?>
        </p>
    <?php else : ?>
        <p class="widget-empty">
            <?php esc_html_e('Gold prices have not been configured yet.', 'traydigita-core'); ?>
        </p>
    <?php endif; ?>
</div>
